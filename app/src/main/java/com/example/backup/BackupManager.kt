package com.example.backup

import android.content.Context
import android.net.Uri
import com.example.data.local.ScanEntity
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.BufferedReader
import java.io.InputStreamReader
import java.io.OutputStreamWriter

data class BackupData(
    val exportTimestamp: Long,
    val appVersion: String,
    val items: List<ScanEntity>
)

object BackupManager {

    suspend fun exportToJson(
        context: Context,
        uri: Uri,
        scans: List<ScanEntity>,
        includeSensitive: Boolean = false
    ): Boolean = withContext(Dispatchers.IO) {
        try {
            val root = JSONObject()
            root.put("version", "1.0")
            root.put("appName", "OfflineQR")
            root.put("exportTimestamp", System.currentTimeMillis())

            val array = JSONArray()
            for (scan in scans) {
                // If sensitive and not requested to include, skip or sanitize
                if (scan.isSensitive && !includeSensitive) {
                    continue
                }
                val itemObj = JSONObject().apply {
                    put("content", scan.content)
                    put("rawFormat", scan.rawFormat)
                    put("contentType", scan.contentType)
                    put("title", scan.title)
                    put("timestamp", scan.timestamp)
                    put("isFavorite", scan.isFavorite)
                    put("isSensitive", scan.isSensitive)
                }
                array.put(itemObj)
            }
            root.put("items", array)

            context.contentResolver.openOutputStream(uri)?.use { outputStream ->
                OutputStreamWriter(outputStream, Charsets.UTF_8).use { writer ->
                    writer.write(root.toString(2))
                    writer.flush()
                }
            }
            true
        } catch (e: Exception) {
            e.printStackTrace()
            false
        }
    }

    suspend fun importFromJson(
        context: Context,
        uri: Uri
    ): Result<List<ScanEntity>> = withContext(Dispatchers.IO) {
        try {
            val content = StringBuilder()
            context.contentResolver.openInputStream(uri)?.use { inputStream ->
                BufferedReader(InputStreamReader(inputStream, Charsets.UTF_8)).use { reader ->
                    var line = reader.readLine()
                    var bytesRead = 0
                    // Limit max read size to 10MB to prevent OutOfMemory attacks
                    while (line != null) {
                        bytesRead += line.length
                        if (bytesRead > 10 * 1024 * 1024) {
                            return@withContext Result.failure(Exception("Backup file exceeds 10MB limit"))
                        }
                        content.append(line)
                        line = reader.readLine()
                    }
                }
            }

            val root = JSONObject(content.toString())
            if (!root.has("items")) {
                return@withContext Result.failure(Exception("Invalid backup format: missing 'items' array"))
            }

            val array = root.getJSONArray("items")
            val list = mutableListOf<ScanEntity>()

            for (i in 0 until array.length()) {
                val item = array.getJSONObject(i)
                val scanContent = item.optString("content", "")
                if (scanContent.isBlank()) continue

                val rawFormat = item.optString("rawFormat", "QR_CODE")
                val contentType = item.optString("contentType", "TEXT")
                val title = item.optString("title", "Scanned Item")
                val timestamp = item.optLong("timestamp", System.currentTimeMillis())
                val isFavorite = item.optBoolean("isFavorite", false)
                val isSensitive = item.optBoolean("isSensitive", false)

                list.add(
                    ScanEntity(
                        id = 0, // Generated by Room
                        content = scanContent,
                        rawFormat = rawFormat,
                        contentType = contentType,
                        title = title,
                        timestamp = timestamp,
                        isFavorite = isFavorite,
                        isSensitive = isSensitive
                    )
                )
            }

            Result.success(list)
        } catch (e: Exception) {
            Result.failure(Exception("Failed to parse backup: ${e.localizedMessage}"))
        }
    }
}
